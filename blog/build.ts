/**
 * Blog generator.
 *
 * Reads Markdown posts from blog/posts/, renders them through the HTML in
 * blog/templates/, and writes:
 *
 *   blog/<slug>/index.html   one page per post
 *   blog/index.html          the index, newest first
 *
 * Images that live next to a post (blog/posts/<name>/…) are copied into the
 * post's output directory, so `![](diagram.svg)` just works. An image whose
 * paragraph contains only the image and that has a title becomes a <figure>
 * with the title as its <figcaption>.
 *
 * Math is rendered to static HTML at build time with KaTeX ($…$ inline,
 * $$…$$ or \[…\] display, \(…\) inline). It is pulled out before Markdown
 * runs so that backslash escapes and * / _ inside equations survive.
 *
 * Generated files carry a marker comment and are safe to overwrite — never
 * edit them by hand, edit the sources. Run with `bun run build` (the `dev`
 * and `start` scripts build first, so this usually happens for you).
 *
 * Front matter (optional, `---` delimited at the top of the file):
 *
 *   title:        display title (defaults to the filename)
 *   date:         YYYY-MM-DD (defaults to the file's mtime)
 *   description:  index subtitle and <meta name="description">
 *   slug:         URL segment (defaults to a slug of the filename)
 *   draft:        true to skip this post entirely
 */

import { cp, mkdir, rm, stat } from "node:fs/promises";
import katex from "katex";

const ROOT = import.meta.dir; // .../blog
const POSTS = `${ROOT}/posts`;
const TEMPLATES = `${ROOT}/templates`;
const KATEX_CSS = `${ROOT}/../assets/katex/katex.min.css`;

/** Stamped at the top of every generated file so cleanup can tell ours
 *  apart from anything hand-written. */
const MARKER = "<!-- Generated by blog/build.ts — edit the sources, not this file. -->";

interface Post {
  slug: string;
  base: string; // source filename without .md, also the asset dir name
  title: string;
  date: string; // YYYY-MM-DD
  description: string;
  body: string; // Markdown
}

interface MathBlock {
  html: string;
  display: boolean;
}

/** Split a `---` delimited front-matter block from the post body. */
function parseFrontMatter(raw: string): { data: Record<string, string>; body: string } {
  const match = /^---\r?\n([\s\S]*?)\r?\n---[ \t]*\r?\n?/.exec(raw);
  if (!match) return { data: {}, body: raw };

  const data: Record<string, string> = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const at = line.indexOf(":");
    if (at === -1) continue;
    const key = line.slice(0, at).trim().toLowerCase();
    const value = line.slice(at + 1).trim().replace(/^(["'])(.*)\1$/, "$2");
    if (key) data[key] = value;
  }
  return { data, body: raw.slice(match[0].length) };
}

/** "Hello, World!" -> "hello-world" */
function slugify(input: string): string {
  return (
    input
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "post"
  );
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Replace {{name}} placeholders; unknown names collapse to "". */
function render(template: string, vars: Record<string, string>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => vars[key] ?? "");
}

/* ---------------------------------------------------------------------- *
 * Math
 * ---------------------------------------------------------------------- */

// $$…$$ and \[…\] are display; \(…\) and $…$ are inline. The `$` forms skip
// a leading/trailing space so "$5 and $10" is left alone, and are ignored
// when escaped (\$). Display alternatives come first so $$ wins over $.
const MATH_RE =
  /(?<!\\)\$\$([\s\S]+?)\$\$|\\\[([\s\S]+?)\\\]|\\\(([\s\S]+?)\\\)|(?<!\\)\$(?!\s)([^$]+?)(?<!\s)\$/g;

function renderKatex(tex: string, display: boolean): string {
  try {
    return katex.renderToString(tex, {
      displayMode: display,
      throwOnError: false,
      strict: false,
      trust: false,
    });
  } catch {
    return `<code>${escapeHtml(tex)}</code>`;
  }
}

/** Swap every equation for a placeholder token Markdown won't touch. */
function protectMath(body: string): { text: string; blocks: MathBlock[] } {
  const blocks: MathBlock[] = [];
  const text = body.replace(MATH_RE, (_m, d1, d2, i1, i2) => {
    const display = d1 !== undefined || d2 !== undefined;
    const tex = String(d1 ?? d2 ?? i1 ?? i2 ?? "").trim();
    const index = blocks.push({ html: renderKatex(tex, display), display }) - 1;
    return `@@KATEX:${index}@@`;
  });
  return { text, blocks };
}

/** Put the rendered math back, unwrapping lone display equations. */
function injectMath(html: string, blocks: MathBlock[]): string {
  if (blocks.length === 0) return html;
  return html
    .replace(/<p>\s*@@KATEX:(\d+)@@\s*<\/p>/g, (m, n: string) =>
      blocks[Number(n)]?.display ? blocks[Number(n)].html : m,
    )
    .replace(/@@KATEX:(\d+)@@/g, (_m, n: string) => blocks[Number(n)]?.html ?? "");
}

/** Lazy-load images; turn a title-bearing standalone image into a figure. */
function enhanceImages(html: string): string {
  html = html.replace(/<p>\s*(<img\b[^>]*>)\s*<\/p>/g, (_m, img: string) => {
    const title = /\btitle="([^"]*)"/.exec(img)?.[1];
    const lazy = img
      .replace(/\s*\btitle="[^"]*"/, "")
      .replace(/^<img\b/, '<img loading="lazy" decoding="async"');
    return title
      ? `<figure>${lazy}<figcaption>${title}</figcaption></figure>`
      : `<p>${lazy}</p>`;
  });
  return html.replace(/<img\b(?! loading=)/g, '<img loading="lazy" decoding="async"');
}

/* ---------------------------------------------------------------------- *
 * Posts
 * ---------------------------------------------------------------------- */

/** Read and normalize every non-draft post, newest first. */
async function loadPosts(): Promise<Post[]> {
  await mkdir(POSTS, { recursive: true });

  const posts: Post[] = [];
  for await (const name of new Bun.Glob("*.md").scan(POSTS)) {
    const file = Bun.file(`${POSTS}/${name}`);
    const { data, body } = parseFrontMatter(await file.text());

    if (/^(true|yes|1)$/i.test(data.draft ?? "")) continue;

    const base = name.replace(/\.md$/, "");
    const title = data.title?.trim() || base;
    let date = data.date?.trim() || "";
    if (!date) {
      date = (await file.stat()).mtime.toISOString().slice(0, 10);
      console.warn(`  ! ${name}: no "date" in front matter, using mtime (${date})`);
    }

    posts.push({
      slug: data.slug?.trim() || slugify(base),
      base,
      title,
      date,
      description: data.description?.trim() || "",
      body,
    });
  }

  posts.sort((a, b) =>
    a.date === b.date ? a.slug.localeCompare(b.slug) : a.date < b.date ? 1 : -1,
  );
  return posts;
}

/** Markup for the index list, or an empty state when there's nothing. */
function indexList(posts: Post[]): string {
  if (posts.length === 0) {
    return `  <p class="bio">Nothing here yet. <a href="/">Go home</a>.</p>`;
  }

  const rows = posts
    .map((p) => {
      const label = p.description ? `<span class="lbl">${escapeHtml(p.description)}</span>` : "";
      return `    <li>
      <a class="row-link" href="/blog/${p.slug}/">
        <span>${escapeHtml(p.title)}${label}</span>
        <span class="yr">${p.date}</span>
      </a>
    </li>`;
    })
    .join("\n");

  return `  <ul class="rows">\n${rows}\n  </ul>`;
}

/** Delete generated post directories whose slug no longer exists. */
async function pruneStale(current: Set<string>): Promise<void> {
  for await (const rel of new Bun.Glob("*/index.html").scan(ROOT)) {
    const slug = rel.slice(0, rel.indexOf("/"));
    if (slug === "posts" || slug === "templates" || current.has(slug)) continue;

    const text = await Bun.file(`${ROOT}/${rel}`).text();
    if (!text.startsWith(MARKER)) continue; // hand-written, leave it alone

    await rm(`${ROOT}/${slug}`, { recursive: true, force: true });
    console.log(`  - removed stale blog/${slug}/`);
  }
}

/** Render one post page and copy its co-located assets alongside. */
async function writePost(post: Post, template: string, usedMath: { value: boolean }): Promise<void> {
  const dir = `${ROOT}/${post.slug}`;

  const existing = Bun.file(`${dir}/index.html`);
  if ((await existing.exists()) && !(await existing.text()).startsWith(MARKER)) {
    console.warn(`  ! blog/${post.slug}/ was not generated by us — skipping`);
    return;
  }

  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });

  // copy any images / files that sit next to the post source
  const assetsDir = `${POSTS}/${post.base}`;
  if ((await stat(assetsDir).catch(() => null))?.isDirectory()) {
    await cp(assetsDir, dir, { recursive: true });
  }

  const { text, blocks } = protectMath(post.body);
  const hasMath = blocks.length > 0;
  usedMath.value ||= hasMath;

  const content = enhanceImages(injectMath(Bun.markdown.html(text), blocks));
  const html = render(template, {
    title: escapeHtml(post.title),
    description: escapeHtml(post.description || post.title),
    date: post.date,
    isoDate: post.date,
    content,
    mathStyle: hasMath ? `<link rel="stylesheet" href="/assets/katex/katex.min.css">` : "",
  });

  await Bun.write(`${dir}/index.html`, `${MARKER}\n${html}`);
  console.log(`  + blog/${post.slug}/${hasMath ? " (math)" : ""}`);
}

async function build(): Promise<void> {
  const posts = await loadPosts();

  const [postTpl, indexTpl] = await Promise.all([
    Bun.file(`${TEMPLATES}/post.html`).text(),
    Bun.file(`${TEMPLATES}/index.html`).text(),
  ]);

  const usedMath = { value: false };
  for (const post of posts) {
    await writePost(post, postTpl, usedMath);
  }

  const index = render(indexTpl, { posts: indexList(posts), count: String(posts.length) });
  await Bun.write(`${ROOT}/index.html`, `${MARKER}\n${index}`);
  console.log(`  + blog/index.html (${posts.length} post${posts.length === 1 ? "" : "s"})`);

  await pruneStale(new Set(posts.map((p) => p.slug)));

  if (usedMath.value && !(await Bun.file(KATEX_CSS).exists())) {
    console.warn("  ! math found but assets/katex/ is missing — run `bun run vendor`");
  }
}

await build();
