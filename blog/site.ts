/**
 * Site-wide constants, and the three files that describe the site to the
 * outside world: sitemap.xml, robots.txt and the RSS feed.
 *
 * The origin is resolved in this order:
 *
 *   1. SITE_URL                     — set this for a custom domain
 *   2. VERCEL_PROJECT_PRODUCTION_URL — Vercel's own production domain, so a
 *                                      preview build still advertises prod
 *   3. the committed default         — so a plain local build already emits
 *                                      real absolute URLs
 *
 * Every absolute link the site publishes (canonical, og:url, the feed, the
 * sitemap) goes through `absolute()` here, so there is one place to change.
 *
 * Output is deterministic: nothing is stamped with the build time, so
 * rebuilding without editing a post leaves these files untouched.
 */

export const SITE = {
  name: "Fabian Aprilliano",
  title: "Fabian Aprilliano — helscape",
  description: "Network engineering, infrastructure automation, distributed systems.",
  language: "en",
  /** Used when neither SITE_URL nor Vercel supplies an origin. */
  defaultOrigin: "https://helscape-portofolio.vercel.app",
};

export const ORIGIN: string = (() => {
  const explicit = process.env.SITE_URL?.trim();
  if (explicit) return explicit.replace(/\/+$/, "");

  const vercel = process.env.VERCEL_PROJECT_PRODUCTION_URL?.trim();
  if (vercel) return `https://${vercel.replace(/\/+$/, "")}`;

  return SITE.defaultOrigin;
})();

/** `/blog/x/` -> `https://example.com/blog/x/` */
export function absolute(path: string): string {
  return ORIGIN + (path.startsWith("/") ? path : `/${path}`);
}

export interface FeedItem {
  slug: string;
  title: string;
  date: string; // YYYY-MM-DD
  description: string;
}

const GENERATED = "Generated by blog/build.ts — edit the sources, not this file.";

function esc(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function postUrl(item: FeedItem): string {
  return absolute(`/blog/${item.slug}/`);
}

function pubDate(date: string): string {
  return new Date(`${date}T00:00:00Z`).toUTCString();
}

/**
 * RSS 2.0. Descriptions are summaries, not full text — the point is to let
 * people follow the blog, not to republish it.
 */
export function rss(items: FeedItem[]): string {
  const entries = items
    .map((item) => {
      const description = item.description
        ? `\n      <description>${esc(item.description)}</description>`
        : "";
      return `    <item>
      <title>${esc(item.title)}</title>
      <link>${postUrl(item)}</link>
      <guid isPermaLink="true">${postUrl(item)}</guid>
      <pubDate>${pubDate(item.date)}</pubDate>${description}
    </item>`;
    })
    .join("\n");

  const body = entries ? `${entries}\n  ` : "";

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${esc(SITE.title)}</title>
    <link>${absolute("/blog/")}</link>
    <description>${esc(SITE.description)}</description>
    <language>${SITE.language}</language>
    <lastBuildDate>${items[0] ? pubDate(items[0].date) : "Thu, 01 Jan 1970 00:00:00 GMT"}</lastBuildDate>
    <atom:link href="${absolute("/blog/feed.xml")}" rel="self" type="application/rss+xml"/>
${body}</channel>
</rss>
`;
}

/** The home page, the blog index, and one entry per post. */
export function sitemap(items: FeedItem[]): string {
  const pages = [
    { loc: absolute("/"), lastmod: "" },
    { loc: absolute("/blog/"), lastmod: items[0]?.date ?? "" },
    ...items.map((item) => ({ loc: postUrl(item), lastmod: item.date })),
  ];

  const urls = pages
    .map((page) => {
      const lastmod = page.lastmod ? `\n    <lastmod>${page.lastmod}</lastmod>` : "";
      return `  <url>\n    <loc>${esc(page.loc)}</loc>${lastmod}\n  </url>`;
    })
    .join("\n");

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

/** Crawl everything except the moderation page, and point at the sitemap. */
export function robots(): string {
  return `# ${GENERATED}
User-agent: *
Allow: /
Disallow: /admin/

Sitemap: ${absolute("/sitemap.xml")}
`;
}
